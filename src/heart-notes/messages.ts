export function chooseMessage(
  pet: Companion,
  seen: string[],
  random: () => number = Math.random,
): HeartMessage {
  const pool = messages.filter((note) => note.pet === pet);
  const unseen = pool.filter((note) => !seen.includes(note.id));
  const candidates = unseen.length
    ? unseen
    : [...pool]
        .sort((a, b) => seen.indexOf(a.id) - seen.indexOf(b.id))
        .slice(0, 12);
  return candidates[
    Math.min(candidates.length - 1, Math.floor(random() * candidates.length))
  ];
}
